"""Generate the character overview from visible outlines in bundled WOFF2 fonts.

Install once: py -m pip install -r scripts/requirements.txt
Run after replacing fonts: py scripts/generate_glyph_coverage.py
Verify without changing files: py scripts/generate_glyph_coverage.py --check
"""

import argparse
import json
import re
import sys
import unicodedata
from pathlib import Path

try:
    from fontTools.pens.boundsPen import BoundsPen
    from fontTools.ttLib import TTFont
except ImportError as error:
    raise SystemExit("Install dependencies first: py -m pip install -r scripts/requirements.txt") from error


FRONTEND = Path(__file__).resolve().parents[1]
FONTS = FRONTEND / "src" / "assets" / "fonts"
OUTPUT = FRONTEND / "src" / "data" / "glyphCoverageData.js"
FONT_STYLES = {
    "unbounded": {style: "unbounded/Unbounded-Variable.woff2" for style in ("Light", "Regular", "Bold")},
    "roboto-condensed-russo-one": {
        "Roboto Condensed SemiBold": "roboto-condensed/RobotoCondensed-Variable.woff2",
        "Russo One Regular": "russo-one/RussoOne-Regular.woff2",
    },
    "source-serif-4": {
        style: "source-serif-4/SourceSerif4-Italic-Variable.woff2" if "Italic" in style else "source-serif-4/SourceSerif4-Variable.woff2"
        for style in ("Regular", "Regular Italic", "Medium", "Medium Italic", "Bold", "Bold Italic", "Black", "Black Italic")
    },
    "ruslan-display": {"Regular": "ruslan-display/RuslanDisplay-Regular.woff2"},
    "inter": {
        style: "inter/Inter-Italic-Variable.woff2" if "Italic" in style else "inter/Inter-Variable.woff2"
        for style in ("Regular", "Regular Italic", "Bold", "Bold Italic")
    },
}

# Match the rendering scale used by CSS so the specimen's cap-height and
# baseline guides describe the displayed glyphs, not their unscaled outlines.
FONT_SIZE_ADJUST = {}
for face in re.findall(r"@font-face\s*\{([^}]+)\}", (FRONTEND / "src/index.css").read_text(encoding="utf-8")):
    source = re.search(r"assets/fonts/([^'\")]+)", face)
    adjustment = re.search(r"size-adjust:\s*([\d.]+)%", face)
    if source:
        FONT_SIZE_ADJUST[source.group(1)] = float(adjustment.group(1)) / 100 if adjustment else 1


def font_data(path):
    font = TTFont(path)
    glyph_set = font.getGlyphSet()
    visible = set()

    for code, glyph_name in font.getBestCmap().items():
        if unicodedata.category(chr(code)) in {"Cc", "Cf", "Cs", "Cn", "Zs", "Zl", "Zp"}:
            continue  # Exclude invisible spacing and control characters, but keep private-use glyphs.

        pen = BoundsPen(glyph_set)
        glyph_set[glyph_name].draw(pen)
        if pen.bounds is not None and pen.bounds[2] > pen.bounds[0] and pen.bounds[3] > pen.bounds[1]:
            visible.add(code)

    metrics = {
        "unitsPerEm": font["head"].unitsPerEm,
        "capHeight": font["OS/2"].sCapHeight,
        "xHeight": font["OS/2"].sxHeight,
        "descent": -font["hhea"].descent,
        "sizeAdjust": FONT_SIZE_ADJUST.get(path.relative_to(FONTS).as_posix(), 1),
    }
    font.close()
    return sorted(visible), metrics


def generated_source():
    lines = [
        "// Generated by scripts/generate_glyph_coverage.py from visible font outlines.",
        "// Run `npm run glyphs:update` after replacing a bundled font file.",
        "export const glyphFontData = {",
    ]

    for family, styles in FONT_STYLES.items():
        lines.append(f"  {json.dumps(family)}: {{")
        for style, relative_path in styles.items():
            path = FONTS / relative_path
            if not path.is_file():
                raise SystemExit(f"Font file not found: {path}")
            codes, metrics = font_data(path)
            lines.append(f"    {json.dumps(style)}: {{")
            lines.append("      codePoints: [")
            for index in range(0, len(codes), 16):
                lines.append("        " + ", ".join(map(str, codes[index:index + 16])) + ",")
            lines.append("      ],")
            lines.append("      metrics: " + json.dumps(metrics, ensure_ascii=False) + ",")
            lines.append("    },")
            print(f"{family} / {style}: {len(codes)} visible characters", file=sys.stderr)
        lines.append("  },")

    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the generated list is stale")
    parser.add_argument("--stdout", action="store_true", help="Print the generated JS without writing it")
    args = parser.parse_args()
    source = generated_source()

    if args.stdout:
        print(source, end="")
    elif args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("Glyph list is stale. Run: npm run glyphs:update")
        print("Glyph list is up to date.")
    else:
        OUTPUT.write_text(source, encoding="utf-8")
        print(f"Updated {OUTPUT.relative_to(FRONTEND)}")


if __name__ == "__main__":
    main()
